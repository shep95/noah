/// A language a person can choose for noah.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Language {
    /// BCP 47 code: ISO 639-1 where one exists, with a region or script where
    /// people commonly need the distinction.
    pub code: &'static str,
    pub english_name: &'static str,
    /// The language's name in itself, which is how people look for it.
    pub native_name: &'static str,
}

const fn language(
    code: &'static str,
    english_name: &'static str,
    native_name: &'static str,
) -> Language {
    Language {
        code,
        english_name,
        native_name,
    }
}

