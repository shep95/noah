NS = 'http://www.sitemaps.org/schemas/sitemap/0.9'
XHTML = 'http://www.w3.org/1999/xhtml'
ET.register_namespace('', NS)
ET.register_namespace('xhtml', XHTML)

# Crawlers that collect pages to train models. Search crawlers (Googlebot,
# Bingbot, Applebot, Yandex, Baidu, Naver's Yeti, Seznam…) are not on this list,
# and Applebot-Extended / Google-Extended only govern training, not search.
AI_TRAINING_AGENTS = (
    'GPTBot', 'ChatGPT-User', 'OAI-SearchBot', 'Google-Extended', 'Applebot-Extended',
    'CCBot', 'ClaudeBot', 'Claude-Web', 'anthropic-ai', 'PerplexityBot', 'Perplexity-User',
    'Bytespider', 'Amazonbot', 'Meta-ExternalAgent', 'Meta-ExternalFetcher', 'FacebookBot',
    'cohere-ai', 'cohere-training-data-crawler', 'Diffbot', 'ImagesiftBot', 'Omgilibot',
    'Timpibot', 'YouBot', 'PetalBot', 'AI2Bot', 'Ai2Bot-Dolma', 'DuckAssistBot', 'MistralAI-User',
)


def url_path(locale, slug):
    """Path of a rendered page (kept for callers of 0.1)."""
    return page_url_path({'render': True}, locale, {'slug': slug})


def as_text(content):
    return html.escape(content, quote=True).replace('\n', '</p><p>')


def alternates_for(page, base, default_locale):
    """hreflang targets of an indexable page: every locale, plus x-default."""
    if not (page['public'] and page['index']):
        return {}
    alternates = {loc: base + page_url_path(page, loc, ent) for loc, ent in page['locales'].items()}
    if len(alternates) > 1 and default_locale in alternates:
        alternates['x-default'] = alternates[default_locale]
    return alternates


def render_page(site_name, page, locale, entry, alternate_urls, base_url, stylesheet=None):
    url = base_url + page_url_path(page, locale, entry)
    head = [
        '<!doctype html>',
        f'<html lang="{html.escape(locale, quote=True)}"><head>',
        '<meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width,initial-scale=1">',
        f'<title>{html.escape(entry["title"])}</title>',
        f'<meta name="description" content="{html.escape(entry["description"], quote=True)}">',
        f'<link rel="canonical" href="{html.escape(url, quote=True)}">',
    ]
    if stylesheet:
        head.append(f'<link rel="stylesheet" href="{html.escape(stylesheet, quote=True)}">')
    if not page['index'] or not page['public']:
        head.append('<meta name="robots" content="noindex,nofollow">')
    else:
        head.append('<meta name="robots" content="index,follow">')
        if len(alternate_urls) > 1:
            head.extend(f'<link rel="alternate" hreflang="{html.escape(code, quote=True)}" href="{html.escape(target, quote=True)}">'
                        for code, target in sorted(alternate_urls.items()))
    # WebPage is a generic schema type. No fabricated authors, reviews, or rich result promises.
    # A JSON-LD data block is not executed, so a script-src policy does not need to allow it.
    graph = {'@context': 'https://schema.org', '@type': 'WebPage', 'url': url, 'inLanguage': locale,
             'name': entry['title'], 'description': entry['description'],
             'isPartOf': {'@type': 'WebSite', 'name': site_name, 'url': base_url + '/'}}
    head.append('<script type="application/ld+json">' + json.dumps(graph, ensure_ascii=False).replace('<', '\\u003c') + '</script>')
    head += ['</head><body>', f'<main><h1>{html.escape(entry["title"])}</h1>',
             f'<p>{as_text(entry["body"])}</p>', f'<p><a href="/">{html.escape(site_name)}</a></p>', '</main></body></html>']
    return '\n'.join(head) + '\n'


def build_sitemap(entries):
    root = ET.Element(f'{{{NS}}}urlset')
    for p in entries:
        node = ET.SubElement(root, f'{{{NS}}}url')
        ET.SubElement(node, f'{{{NS}}}loc').text = p['url']
        if p.get('lastmod'):
            ET.SubElement(node, f'{{{NS}}}lastmod').text = p['lastmod']
        if len(p['alternates']) > 1:
            for code, target in sorted(p['alternates'].items()):
                ET.SubElement(node, f'{{{XHTML}}}link', {'rel': 'alternate', 'hreflang': code, 'href': target})
    return ET.tostring(root, encoding='utf-8', xml_declaration=True)


def build_robots(spec, base):
    policy = spec['robots']
    lines = [f'# generated by usel {__version__} from the site spec; edit the spec, not this file.', '']
    if not policy['allow_search']:
        lines += ['# this site stays out of every index, search engines included.', 'User-agent: *', 'Disallow: /', '']
        return '\n'.join(lines)
    if policy['block_ai_training']:
        lines.append('# model-training and AI-answer crawlers: nothing here may be collected.')
        for agent in list(AI_TRAINING_AGENTS) + list(policy['extra_ai_agents']):
            lines.append(f'User-agent: {agent}')
        lines += ['Disallow: /', '']
    lines.append('# search engines: public pages are crawlable; private surfaces are not.')
    lines += ['User-agent: *', 'Allow: /']
    lines += [f'Disallow: {p}' for p in policy['disallow']]
    lines += ['', f'Sitemap: {base}/sitemap.xml', '']
    return '\n'.join(lines)


def selected_engines(spec):
    engines = load_engines()
    if spec['engines'] == ['all']:
        return engines
    selections = []
    for i in spec['engines']:
        matches = [e for e in engines if e['id'] == i]
        if not matches:
            raise SpecError(f'unknown engine: {i}')
        selections.extend(matches)
    return selections


def engine_report(engines):
    lines = ['# engine-specific instructions', '', 'a shared index or result provider does NOT imply identical SEO rules.',
             'a missing capability (null) means **unknown**, not unsupported.', '',
             'indexing and rankings are not guaranteed by submissions or generated metadata.', '']
    for e in engines:
        caps = e['capabilities']
        status = e['verification']
        lines += [f'## {e["name"]} — {status}',
                  f'- type: {e["kind"]}; result sources: {", ".join(e.get("result_sources", [])) or "unconfirmed"}',
                  f'- XML sitemap: {caps.get("sitemap")}; IndexNow: {caps.get("indexnow")}',
                  f'- specific finding: {e.get("note") or "no individually verified instructions yet"}',
                  f'- sources: {", ".join(x["url"] for x in e.get("evidence", [])) or "research pending"}', '']
    return '\n'.join(lines) + '\n'


def market_coverage(spec, out):
    countries = load_countries()
    targets = spec.get('market_targets', 'all')
    chosen = [c for c in countries if targets == 'all' or c['code'] in targets]
    rows = []
    for c in chosen:
        languages = {x['code'].split('_')[0].split('-')[0] for x in c.get('language_candidates', [])}
        for page in spec['pages']:
            if not page['public'] or not page['index']:
                continue
            local = set(page['locales'])
            specific = sorted(x for x in local if x.upper().endswith('-' + c['code'].upper()))
            shared = sorted(x for x in local if x.split('-')[0] in languages)
            status = 'country_locale' if specific else 'shared_language_only' if shared else 'unlocalized'
            rows.append({'country': c['name'], 'code': c['code'], 'page_id': page['id'],
                         'status': status, 'matched_locales': ','.join(specific or shared),
                         'note': 'shared language alone does not verify local relevance or rankings' if status == 'shared_language_only' else ''})
    with (out / 'market-coverage.csv').open('w', newline='', encoding='utf-8') as file:
        w = csv.DictWriter(file, fieldnames=['country', 'code', 'page_id', 'status', 'matched_locales', 'note'])
        w.writeheader()
        w.writerows(rows)
    return {'targeted_markets': len(chosen), 'country_locale': sum(r['status'] == 'country_locale' for r in rows),
            'shared_language_only': sum(r['status'] == 'shared_language_only' for r in rows),
            'unlocalized': sum(r['status'] == 'unlocalized' for r in rows)}


def _batches(metas, empty_size):
    # Respect both the 50 000-URL limit (conservatively 10 000) and a 9 MB size cap.
    batches, batch, batch_size = [], [], empty_size
    for item in metas:
        item_size = len(build_sitemap([item])) - empty_size
        if item_size + empty_size > 9_000_000:
            raise SpecError('one sitemap entry exceeds conservative size limit')
        if batch and (len(batch) >= 10000 or batch_size + item_size > 9_000_000):
            batches.append(batch)
            batch, batch_size = [], empty_size
        batch.append(item)
        batch_size += item_size
    if batch:
        batches.append(batch)
    return batches


def compile_site(spec, destination, reports=None):
    """Write the public files to ``destination`` and the reports to ``reports``.

    ``reports`` defaults to ``destination`` (0.1 behaviour). Point it elsewhere
    when ``destination`` is a site's public folder: the reports describe your
    SEO plan and do not belong on the web.
    """
    validate_spec(spec)
    base = spec['base_url'].rstrip('/')
    out = Path(destination)
    out.mkdir(parents=True, exist_ok=True)
    report_dir = Path(reports) if reports is not None else out
    report_dir.mkdir(parents=True, exist_ok=True)
    engines = selected_engines(spec)
    default_locale = spec.get('default_locale')
    metas, rendered, routes, rendered_urls = [], 0, [], []
    for page in spec['pages']:
        if not page['public']:
            continue  # private data must never be emitted to a public static build
        alternates = alternates_for(page, base, default_locale)
        for locale, entry in page['locales'].items():
            path = page_url_path(page, locale, entry)
            if page['render']:
                # Hosts decode the request path before looking up the file, so
                # /zh-CN/%E8%AE%A8%E8%AE%BA/ must live in zh-CN/讨论/, not in a
                # percent-encoded folder. Slugs are validated against traversal.
                target = (out / unquote(path).strip('/') / 'index.html').resolve()
                if not target.is_relative_to(out.resolve()):
                    raise SpecError('unsafe path')
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(render_page(spec['site_name'], page, locale, entry, alternates, base, spec.get('stylesheet')), encoding='utf-8')
                rendered += 1
                rendered_urls.append(base + path)
            elif page['index']:
                routes.append(base + path)
            if page['index']:
                metas.append({'id': page['id'], 'locale': locale, 'url': base + path, 'alternates': alternates,
                              'lastmod': page.get('lastmod')})
    write_sitemap = spec['sitemap'] and spec['robots']['allow_search']
    empty_size = len(build_sitemap([]))
    batches = _batches(metas, empty_size) if write_sitemap else []
    sitemaps = []
    for i, part in enumerate(batches, 1):
        name = f'sitemap-{i}.xml' if len(batches) > 1 else 'sitemap.xml'
        (out / name).write_bytes(build_sitemap(part))
        sitemaps.append(name)
    if len(sitemaps) > 1:
        root = ET.Element(f'{{{NS}}}sitemapindex')
        for name in sitemaps:
            sm = ET.SubElement(root, f'{{{NS}}}sitemap')
            ET.SubElement(sm, f'{{{NS}}}loc').text = base + '/' + name
        (out / 'sitemap.xml').write_bytes(ET.tostring(root, encoding='utf-8', xml_declaration=True))
    if write_sitemap and not sitemaps:
        (out / 'sitemap.xml').write_bytes(build_sitemap([]))
    if spec['robots']['manage']:
        (out / 'robots.txt').write_text(build_robots(spec, base), encoding='utf-8')
    if spec.get('indexnow_key') and spec['robots']['allow_search']:
        # IndexNow verifies ownership by fetching /<key>.txt containing the key.
        (out / f"{spec['indexnow_key']}.txt").write_text(spec['indexnow_key'], encoding='utf-8')
    (report_dir / 'engine-guide.md').write_text(engine_report(engines), encoding='utf-8')
    market = market_coverage(spec, report_dir)
    manifest = {
        'compiler': f'usel-{__version__}', 'base_url': base,
        'rendered_pages': rendered, 'indexed_pages': len(metas), 'route_urls': routes,
        'rendered_urls': rendered_urls,
        'robots_managed': spec['robots']['manage'], 'robots_disallow': spec['robots']['disallow'],
        'sitemap_written': write_sitemap, 'allow_search': spec['robots']['allow_search'],
        'engines_selected': len(engines),
        'documented_profiles': len([e for e in engines if e['verification'] == 'documented']),
        'market_coverage': market,
        'unverified_profiles': [e['id'] for e in engines if e['verification'] != 'documented'],
        'note': 'generated SEO hints do not guarantee inclusion, ranking, or submission',
    }
    (report_dir / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding='utf-8')
    # Offline-ready payload only; NO network calls or automatic exposure.
    (report_dir / 'indexnow-plan.json').write_text(json.dumps({
        'supported_participants': [e['id'] for e in engines if e['capabilities'].get('indexnow') is True],
        'hosts_to_notify': 'submissions are opt-in; see CLI submit-indexnow',
        'key': spec.get('indexnow_key'),
        'urlList': [p['url'] for p in metas],
    }, ensure_ascii=False, indent=2), encoding='utf-8')
    return {'files': len([p for p in out.rglob('*') if p.is_file()]), 'indexed_pages': len(metas),
            'rendered_pages': rendered, 'route_urls': len(routes),
            'documented_profiles': manifest['documented_profiles'],
            'engine_profiles': len(engines), 'market_coverage': market,
            'location': str(out), 'reports': str(report_dir)}
